"""Generate the database diagram (D2 source) from the real schema (#57).

Usage:
    uv run python scripts/database_diagram.py
    d2 --layout elk docs/architecture/database.d2 docs/architecture/database.svg

The Ledger and the workload store each create their tables in a temporary SQLite file through
their public constructors; the tables, columns, primary keys and references are then read back
from SQLite, so the diagram cannot drift from the code. tests/unit/test_architecture_diagrams.py
fails when the committed `database.d2` differs from what this script writes.
"""

import sqlite3
import tempfile
from collections.abc import Callable
from contextlib import AbstractContextManager
from pathlib import Path
from typing import NamedTuple

from data_finops.ledger.ledger import Ledger
from data_finops.workload.store import WorkloadStore

TARGET = Path(__file__).resolve().parents[1] / "docs" / "architecture" / "database.d2"


class Owner(NamedTuple):
    """A store that owns tables in the shared file, drawn as one D2 container."""

    container: str
    label: str
    open_store: Callable[[Path], AbstractContextManager[object]]
    """Opening the store on a path creates its tables there."""


class Column(NamedTuple):
    name: str
    kind: str
    primary_key: bool
    not_null: bool
    references: tuple[str, str] | None
    """The (table, column) this column's declared foreign key points to."""


class Table(NamedTuple):
    name: str
    columns: list[Column]


OWNERS = [
    Owner("ledger", "Ledger (billing)", Ledger),
    Owner("workload", "Workload store", WorkloadStore),
]


def _schema(owner: Owner) -> list[Table]:
    """The tables the owner creates, in creation order, as SQLite reports them."""
    with tempfile.TemporaryDirectory() as folder:
        path = Path(folder) / "data-finops.sqlite"
        with owner.open_store(path):
            pass
        connection = sqlite3.connect(path)
        try:
            names = [
                row[0]
                for row in connection.execute(
                    "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY rowid"
                )
            ]
            # Table names come from this temporary file's own catalog, so they are safe to
            # place in a PRAGMA, which takes no parameters.
            tables = []
            for name in names:
                references = {
                    row[3]: (row[2], row[4])
                    for row in connection.execute(f"PRAGMA foreign_key_list({name})")
                }
                columns = [
                    Column(column, kind, bool(key), bool(not_null), references.get(column))
                    for _, column, kind, not_null, _, key in connection.execute(
                        f"PRAGMA table_info({name})"
                    )
                ]
                tables.append(Table(name, columns))
            return tables
        finally:
            connection.close()


def _column_d2(column: Column) -> str:
    constraints = [
        constraint
        for constraint, present in (
            ("primary_key", column.primary_key),
            ("foreign_key", column.references is not None),
            ("not_null", column.not_null and not column.primary_key),
        )
        if present
    ]
    suffix = f" {{constraint: [{'; '.join(constraints)}]}}" if constraints else ""
    # Quoted: columns such as `direction` and `name` are D2 keywords.
    return f'"{column.name}": {column.kind}{suffix}'


def database_d2() -> str:
    """The D2 source of the database diagram."""
    lines = [
        "# Generated by scripts/database_diagram.py from the schema; do not edit by hand.",
        "# One SQLite file; each store owns its tables (ADR 0018 and its amendment).",
        "direction: right",
        "",
    ]
    references = []
    for owner in OWNERS:
        lines.append(f"{owner.container}: {owner.label} {{")
        for table in _schema(owner):
            lines += [f"  {table.name}: {{", "    shape: sql_table"]
            lines += [f"    {_column_d2(column)}" for column in table.columns]
            lines.append("  }")
            references += [
                f'{owner.container}.{table.name}."{column.name}" -> '
                f'{owner.container}.{column.references[0]}."{column.references[1]}"'
                for column in table.columns
                if column.references is not None
            ]
        lines += ["}", ""]
    lines += references
    return "\n".join(lines) + "\n"


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(database_d2(), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
