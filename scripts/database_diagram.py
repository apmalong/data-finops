"""Generate the database diagram (D2 source) from the real schema (#57).

Usage:
    uv run python scripts/database_diagram.py
    d2 --layout elk docs/architecture/database.d2 docs/architecture/database.svg

The Ledger and the workload store each create their tables in a temporary SQLite file through
their public constructors; the tables, columns, primary keys and references are then read back
from SQLite, so the diagram cannot drift from the code. tests/unit/test_architecture_diagrams.py
fails when the committed `database.d2` differs from what this script writes.
"""

import sqlite3
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

from data_finops.ledger.ledger import Ledger
from data_finops.workload.store import WorkloadStore

TARGET = Path(__file__).resolve().parents[1] / "docs" / "architecture" / "database.d2"

# (D2 container, label, constructor that creates the owner's tables)
_OWNERS: list[tuple[str, str, Callable[[Path], Any]]] = [
    ("ledger", "Ledger (billing)", Ledger),
    ("workload", "Workload store", WorkloadStore),
]


def _tables(
    create: Callable[[Path], Any],
) -> list[tuple[str, list[str], list[tuple[str, str]]]]:
    """Each table's D2 column lines and (column, referenced column) pairs, in creation order."""
    with tempfile.TemporaryDirectory() as folder:
        path = Path(folder) / "data-finops.sqlite"
        with create(path):
            pass
        connection = sqlite3.connect(path)
        try:
            names = [
                row[0]
                for row in connection.execute(
                    "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY rowid"
                )
            ]
            tables = []
            for name in names:
                references = {
                    row[3]: (row[2], row[4])
                    for row in connection.execute(f"PRAGMA foreign_key_list({name})")
                }
                columns = []
                for _, column, kind, not_null, _, key in connection.execute(
                    f"PRAGMA table_info({name})"
                ):
                    constraints = [
                        c
                        for c, present in (
                            ("primary_key", key),
                            ("foreign_key", column in references),
                            ("not_null", not_null and not key),
                        )
                        if present
                    ]
                    suffix = f" {{constraint: [{'; '.join(constraints)}]}}" if constraints else ""
                    # Quoted: columns such as `direction` and `name` are D2 keywords.
                    columns.append(f'"{column}": {kind}{suffix}')
                links = [
                    (f'{name}."{column}"', f'{table}."{target}"')
                    for column, (table, target) in references.items()
                ]
                tables.append((name, columns, links))
            return tables
        finally:
            connection.close()


def database_d2() -> str:
    lines = [
        "# Generated by scripts/database_diagram.py from the schema; do not edit by hand.",
        "# One SQLite file; each store owns its tables (ADR 0018 and its amendment).",
        "direction: right",
        "",
    ]
    references = []
    for container, label, create in _OWNERS:
        lines.append(f"{container}: {label} {{")
        for name, columns, links in _tables(create):
            lines += [f"  {name}: {{", "    shape: sql_table"]
            lines += [f"    {column}" for column in columns]
            lines.append("  }")
            references += [
                f"{container}.{source} -> {container}.{target}" for source, target in links
            ]
        lines += ["}", ""]
    lines += references
    return "\n".join(lines) + "\n"


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(database_d2(), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
